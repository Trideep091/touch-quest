import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const filesOrder = [
  'storage.js',
  'audioFeedback.js',
  'badges.js',
  'challengeCategories.js',
  'sampleChallenges.js',
  'challengeHistory.js',
  'playerProgress.js',
  'challengeGenerator.js',
  'photoVerification.js',
  'Confetti.js',
  'QuestManager.js',
  'Navbar.js',
  'Hero.js',
  'HowItWorks.js',
  'LevelCards.js',
  'AntiScreenSection.js',
  'OpenAISection.js',
  'NextQuestPreview.js',
  'BadgeCollection.js',
  'PlayerProfile.js',
  'app.js'
];

let bundleContent = `/**
 * TouchQuest Standalone Client Bundle
 * Autogenerated to allow TouchQuest to run seamlessly both:
 * 1. Directly from the local folder via file:/// protocol (without CORS restrictions)
 * 2. Served via local/remote HTTP web servers (http://localhost:3000)
 */
(function() {
  'use strict';

`;

for (const file of filesOrder) {
  const filePath = path.join(__dirname, file);
  if (!fs.existsSync(filePath)) {
    console.error(`File missing: ${filePath}`);
    process.exit(1);
  }

  let content = fs.readFileSync(filePath, 'utf-8');

  // Strip import statements
  content = content.replace(/^import\s+.*?;\s*$/gm, '');

  // Strip export keywords
  content = content.replace(/^export\s+const\s+/gm, 'const ');
  content = content.replace(/^export\s+function\s+/gm, 'function ');
  content = content.replace(/^export\s+class\s+/gm, 'class ');
  content = content.replace(/^export\s+\{.*?\};?\s*$/gm, '');
  content = content.replace(/^export\s+default\s+.*?;?\s*$/gm, '');

  bundleContent += `  // ==========================================\n`;
  bundleContent += `  // MODULE: ${file}\n`;
  bundleContent += `  // ==========================================\n`;
  bundleContent += content + '\n\n';
}

bundleContent += `
  // Immediate / DOMContentLoaded Bootstrapper
  function bootTouchQuest() {
    if (typeof document !== 'undefined') {
      const mainMount = document.getElementById('main-content');
      if (mainMount && !mainMount.hasAttribute('data-booted')) {
        mainMount.setAttribute('data-booted', 'true');
        const app = new TouchQuestApp();
        app.init();
      }
    }
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', bootTouchQuest);
  } else {
    bootTouchQuest();
  }
})();
`;

const outputPath = path.join(__dirname, 'touchquest.bundle.js');
fs.writeFileSync(outputPath, bundleContent, 'utf-8');
console.log(`Bundle generated successfully at ${outputPath} (${bundleContent.length} bytes)!`);
